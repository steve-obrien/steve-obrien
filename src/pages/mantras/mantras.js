const allMantras = [];

for (const group of mantraGroups) {
	for (const mantra of group.mantras) {
		allMantras.push({
			...mantra,
			groupSlug: group.slug,
			groupTitle: group.title,
		});
	}
}

export const mantras = allMantras;

/**
 * Find one published mantra by its stable URL slug.
 *
 * @param {string} slug - Mantra slug from the active route.
 * @returns {object | undefined} Matching mantra record when one exists.
 */
export function findMantra(slug) {
	return mantras.find((mantra) => mantra.slug === slug);
}
